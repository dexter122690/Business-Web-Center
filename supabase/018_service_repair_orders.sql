-- Service repair orders / job cards linked to invoices and branches.
-- Run after migrations 002 through 017.

begin;

create table if not exists public.service_repair_orders (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses(id) on delete cascade,
  branch_id uuid not null references public.branches(id) on delete restrict,
  invoice_id uuid not null references public.invoices(id) on delete restrict,
  repair_order_number bigint generated by default as identity unique,
  contractor text not null default '',
  labor_cost numeric(14,2) not null default 0 check (labor_cost >= 0),
  promise_date date,
  job_instructions text not null default '',
  remarks text not null default '',
  status text not null default 'Open' check (status in ('Open', 'In progress', 'Completed', 'Cancelled')),
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (business_id, branch_id, invoice_id)
);

create index if not exists service_repair_orders_branch_date_idx
  on public.service_repair_orders (business_id, branch_id, created_at desc);

drop trigger if exists set_service_repair_orders_updated_at on public.service_repair_orders;
create trigger set_service_repair_orders_updated_at
before update on public.service_repair_orders
for each row execute procedure public.set_updated_at();

alter table public.service_repair_orders enable row level security;

drop policy if exists service_repair_orders_read on public.service_repair_orders;
create policy service_repair_orders_read on public.service_repair_orders
for select to authenticated
using (public.is_platform_admin() or public.is_business_member(business_id));

drop policy if exists service_repair_orders_insert on public.service_repair_orders;
create policy service_repair_orders_insert on public.service_repair_orders
for insert to authenticated
with check (
  (public.is_platform_admin() or public.is_business_manager(business_id))
  and created_by = auth.uid()
  and exists (
    select 1 from public.branches br
    where br.id = branch_id and br.business_id = business_id and br.is_active
  )
);

drop policy if exists service_repair_orders_update on public.service_repair_orders;
create policy service_repair_orders_update on public.service_repair_orders
for update to authenticated
using (public.is_platform_admin() or public.is_business_manager(business_id))
with check (
  (public.is_platform_admin() or public.is_business_manager(business_id))
  and exists (
    select 1 from public.branches br
    where br.id = branch_id and br.business_id = business_id and br.is_active
  )
);

drop policy if exists service_repair_orders_delete on public.service_repair_orders;
create policy service_repair_orders_delete on public.service_repair_orders
for delete to authenticated
using (public.is_platform_admin() or public.is_business_manager(business_id));

commit;
